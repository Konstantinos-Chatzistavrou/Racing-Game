std::string apply_tune(const std::string& car_json, const Tune& t) {
    json d = json::parse(car_json);
    json& brakes = d.at("brakes");
    brakes["bias_front"] = std::clamp(brakes.at("bias_front").get<double>() + step(kBrakeBiasSteps, t.brake_bias), 0.5, 0.8);

    json& dt = d.at("drivetrain");
    double fd = dt.at("final_drive").get<double>() * step(kGearingSteps, t.gearing);
    dt["final_drive"] = std::round(fd * 100.0) / 100.0;

    const double k = step(kSuspensionSteps, t.suspension);
    for (const char* ax : {"front_axle", "rear_axle"})
        for (const char* key : {"spring_rate_n_per_m", "damper_bump_ns_per_m", "damper_rebound_ns_per_m"}) {
            json& v = d.at(ax).at(key);
            v = std::round(v.get<double>() * k);
        }

    // Anti-roll balance: the stiffer end of the car takes more of the load transfer and loses grip
    // first (front -> understeer, rear -> oversteer).
    json& arb_f = d.at("front_axle").at("anti_roll_rate_n_per_m");
    json& arb_r = d.at("rear_axle").at("anti_roll_rate_n_per_m");
    switch (clamp3(t.arb)) {
        case 0: arb_f = arb_f.get<double>() * 1.3; arb_r = arb_r.get<double>() * 0.8; break;
        case 2: arb_f = arb_f.get<double>() * 0.8; arb_r = arb_r.get<double>() * 1.3; break;
        default: break;
    }

    // Differential: only a limited-slip diff has settings to change.
    for (const char* name : {"rear_diff", "front_diff"}) {
        if (!dt.contains(name) || dt[name].value("type", "") != "lsd") continue;
        json& df = dt[name];
        switch (clamp3(t.diff)) {
            case 0:
                df["preload_nm"] = df.value("preload_nm", 0.0) * 0.4;
                df["power_ramp"] = df.value("power_ramp", 0.0) * 0.5;
                df["coast_ramp"] = df.value("coast_ramp", 0.0) * 0.5;
                break;
            case 2:
                df["preload_nm"] = df.value("preload_nm", 0.0) * 2.0;
                df["power_ramp"] = std::min(df.value("power_ramp", 0.0) * 1.8, 0.9);
                df["coast_ramp"] = std::min(df.value("coast_ramp", 0.0) * 1.8, 0.9);
                break;
            default: break;
        }
    }
    d["notes"] = "Tuned copy (brake_bias " + std::to_string(t.brake_bias) + ", gearing " + std::to_string(t.gearing) +
                 ", suspension " + std::to_string(t.suspension) + ", arb " + std::to_string(t.arb) + ", diff " +
                 std::to_string(t.diff) + "). Generated by rs::apply_tune; do not edit.";
    return d.dump(2);
}

CarStats car_stats(const CarConfig& c) {
    CarStats s;
    s.name = c.name;
    s.layout = c.drivetrain.layout;
    std::transform(s.layout.begin(), s.layout.end(), s.layout.begin(), [](unsigned char ch) { return std::toupper(ch); });
    for (const auto& [rpm, nm] : c.engine.torque_curve) {
        double kw = nm * rpm * 2.0 * kPi / 60.0 / 1000.0;
        if (kw > s.peak_power_kw) { s.peak_power_kw = kw; s.peak_power_rpm = rpm; }
        s.peak_torque_nm = std::max(s.peak_torque_nm, nm);
    }
    s.mass_kg = c.mass;
    s.power_to_weight = s.peak_power_kw * 1000.0 / c.mass;
    s.grip = 0.5 * (c.tire_front.mu_y + c.tire_rear.mu_y);
    s.downforce_area = c.aero.lift_area;
    s.brake_bias_front = c.brake_bias_front;
    return s;
}

std::vector<Rival> parse_rivals(const std::string& text) {
    json j = json::parse(text);
    if (j.value("schema", "") != "rivals/1") throw std::runtime_error("rivals: expected \"schema\": \"rivals/1\"");
    std::vector<Rival> out;
    for (const json& r : j.at("rivals")) {
        Rival v;
        v.name = r.at("name").get<std::string>();
        AIParams& p = v.params;
        p.skill = r.value("skill", p.skill);
        p.reaction_time = r.value("reaction_time", p.reaction_time);
        p.headway = r.value("headway", p.headway);
        p.aggression = r.value("aggression", p.aggression);
        p.lane_offset = r.value("lane_offset", p.lane_offset);
        if (p.skill <= 0 || p.skill > 1.0) throw std::runtime_error("rivals: " + v.name + ": skill must be in (0, 1]");
        out.push_back(v);
    }
    if (out.empty()) throw std::runtime_error("rivals: list is empty");
    return out;
}

std::vector<Rival> load_rivals(const std::string& path) { return parse_rivals(read_file(path, "rivals")); }

AIParams apply_difficulty(AIParams p, int difficulty) {
    switch (difficulty) {
        case kEasy:
            p.skill -= 0.05;
            p.reaction_time += 0.15;
            p.aggression *= 0.6;
            break;
        case kHard:
            p.skill = std::min(p.skill + 0.02, 0.985);
            p.reaction_time = std::max(p.reaction_time - 0.1, 0.25);
            p.aggression = std::min(p.aggression + 0.1, 1.0);
            break;
        default: break;
    }
    return p;
}

EventSetup make_event(int mode, int laps, int rivals, int grid_slot) {
    EventSetup e;
    e.laps = std::max(laps, 1);
    switch (mode) {
        case kTimeAttack:
            e.cars = 1;
            e.player_index = 0;
            break;
        case kPackRace:
            e.cars = kMaxCars;
            e.player_index = kMaxCars - 1;
            break;
        default:
            e.cars = std::clamp(rivals, 1, kMaxCars - 1) + 1;
            e.player_index = std::clamp(grid_slot, 0, e.cars - 1);
            break;
    }
    return e;
}

