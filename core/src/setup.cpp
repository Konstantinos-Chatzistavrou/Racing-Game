template <size_t N>
double step(const std::array<double, N>& table, int i) {
    return table[std::clamp(i, 0, static_cast<int>(N) - 1)];
}
int clamp3(int i) { return std::clamp(i, 0, 2); }
std::string read_file(const std::string& path, const char* what) {
    std::ifstream f(path);
    if (!f) throw std::runtime_error(std::string(what) + ": cannot open " + path);
    std::stringstream ss;
    ss << f.rdbuf();
    return ss.str();
}
