// Gameplay numbers of the generated parts (downforce, drag, mass) -> web/src/parts-metrics.ts.
//   cd web && node --experimental-strip-types scripts/metrics.mjs
// Wings and rims are measured from their geometry on a reference car (bounding-box areas and volumes with lift / drag /
// density coefficients). Splitters, diffusers, skirts and body panels are fitted to each car at run time
// (scene/parts/fit.ts), so they have no single geometry to measure: their entries in parts-metrics.ts are kept as they are.
import * as THREE from 'three/webgpu';
import fs from 'node:fs';
import { WING_SPECS } from '../src/scene/parts/wings.ts';
import { RIM_SPECS } from '../src/scene/parts/rims.ts';

const target = new URL('../src/parts-metrics.ts', import.meta.url);
const old = fs.readFileSync(target, 'utf8');
const out = JSON.parse(old.slice(old.indexOf('= {') + 2, old.lastIndexOf('}') + 1));
const box = new THREE.Box3(new THREE.Vector3(-0.95, 0, -2.2), new THREE.Vector3(0.95, 1.3, 2.2));
const wb = new THREE.Box3(new THREE.Vector3(-0.88, 0.92, -2.12), new THREE.Vector3(0.88, 1.06, -1.7));
const mat = new THREE.MeshBasicMaterial();
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const size = (g) => new THREE.Box3().setFromObject(g).getSize(new THREE.Vector3());
for (const s of WING_SPECS) {
  const z = size(s.build({ box, wb, mat }));
  out[s.id] = { df: +clamp(z.x * z.z * 0.22, 0, 0.22).toFixed(3), drag: +clamp(z.x * z.y * 0.1, 0, 0.09).toFixed(3), kg: +clamp(z.x * z.y * z.z * 25, 0, 6).toFixed(2) };
}
for (const s of RIM_SPECS) {
  const z = size(s.build({ radius: 0.34, width: 0.22, mat }));
  out[s.id] = { df: 0, drag: 0, kg: +clamp(z.x * z.y * z.z * 260, 0, 3).toFixed(2) };
}
fs.writeFileSync(target, '// Measured from the generated geometry (bbox areas and volumes with lift/drag/density coefficients).\n// Generated by scripts/metrics.mjs; re-run after changing a wing or rim design.\nexport interface PartMetric { df: number; drag: number; kg: number }\nexport const PART_METRICS: Record<string, PartMetric> = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('parts', Object.keys(out).length);
